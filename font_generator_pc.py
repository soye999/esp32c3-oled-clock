# -*- coding: utf-8 -*-
from PIL import Image, ImageFont, ImageDraw
import os

# 16x16 中文字库：保留原有欢迎语字符，并加入时钟需要的日期/星期用字
TEXT_ZH = '你好欢迎使用ESP32C3世界点亮成功！年月日星期一二三四五六'
SIZE_ZH = 16

# 24x32 大号数字字库：用于时钟主显示
TEXT_TIME = '0123456789:'
TIME_W, TIME_H = 24, 32

OUTPUT_FILE = 'fonts_zh.py'

FONT_PATHS = [
    'C:/Windows/Fonts/simhei.ttf', 'C:/Windows/Fonts/msyh.ttc',
    'C:/Windows/Fonts/simsun.ttc', 'C:/Windows/Fonts/msyhbd.ttc',
]

def find_font():
    for p in FONT_PATHS:
        if os.path.exists(p):
            print('Font:', p)
            return p
    raise FileNotFoundError('No Chinese font found')

def char_to_vlsb(char, font, width, height):
    img = Image.new('1', (width, height), 0)
    draw = ImageDraw.Draw(img)
    bbox = draw.textbbox((0, 0), char, font=font)
    tw, th = bbox[2] - bbox[0], bbox[3] - bbox[1]
    x = (width - tw) // 2 - bbox[0]
    y = (height - th) // 2 - bbox[1]
    draw.text((x, y), char, font=font, fill=1)
    pixels = []
    # MONO_VLSB 要求按页存放：先页 0 的所有列，再页 1 的所有列
    for page in range(height // 8):
        for col in range(width):
            bv = 0
            for bit in range(8):
                row = page * 8 + bit
                if row < height and img.getpixel((col, row)):
                    bv |= (1 << bit)
            pixels.append(bv)
    return pixels

def gen_zh(font_path):
    chars = sorted(set(TEXT_ZH), key=TEXT_ZH.index)
    font = ImageFont.truetype(font_path, SIZE_ZH)
    items = []
    for c in chars:
        if ord(c) < 128:
            continue
        code = int(c.encode('utf-8').hex(), 16)
        data = char_to_vlsb(c, font, SIZE_ZH, SIZE_ZH)
        items.append((code, data))
        print(f'  [ZH] {c} 0x{code:X} -> {len(data)} bytes')
    return items

def gen_time(font_path):
    font = ImageFont.truetype(font_path, TIME_H)
    items = []
    for c in TEXT_TIME:
        data = char_to_vlsb(c, font, TIME_W, TIME_H)
        items.append((ord(c), data))
        print(f'  [TIME] {c!r} -> {len(data)} bytes')
    return items

def write_dict(f, name, items, value_width):
    f.write('%s = {\n' % name)
    for i, (code, data) in enumerate(items):
        hex_b = ', '.join('0x%02X' % b for b in data)
        comma = ',' if i < len(items) - 1 else ''
        f.write('    0x%X: [%s]%s\n' % (code, hex_b, comma))
    f.write('}\n\n')

def main():
    font_path = find_font()
    zh_items = gen_zh(font_path)
    time_items = gen_time(font_path)

    with open(OUTPUT_FILE, 'w', encoding='utf-8') as f:
        f.write('# 中文 16x16 点阵 + 时钟 24x32 数字点阵 (MONO_VLSB)\n')
        f.write('# Auto-generated by font_generator_pc.py\n')
        f.write('# FONT_ZH: 中文 16x16, key 为 UTF-8 编码\n')
        f.write('# FONT_TIME24: 数字/冒号 24x32, key 为 ASCII 码\n\n')
        write_dict(f, 'FONT_ZH', zh_items, SIZE_ZH)
        write_dict(f, 'FONT_TIME24', time_items, TIME_W)

    print('\nDone! %d 个汉字 + %d 个数字字符 -> %s' %
          (len(zh_items), len(time_items), os.path.abspath(OUTPUT_FILE)))

if __name__ == '__main__':
    main()
